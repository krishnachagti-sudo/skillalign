"""Does the method find real trends and ignore fake ones?

The sample postings are synthetic, so on their own they prove nothing:
any trend the tool reports was written into the generator. This script
asks the questions a sceptical judge would ask, and writes the answers
to docs/validation.md:

1. Null test: on data with NO trends (generator --flat), how many
   "emerging"/"declining" skills and Review/Prepare advice does the tool
   still produce? Compared with the naive rule SkillAlign first used
   (growth thresholds only, no significance test).
2. Recovery: on trended data, are the trends it reports ones the
   generator really contains?
3. Stability: across 20 different random samples, how much do the
   course scores move, and how often does each course get the same grade?

Run:  python tools/validate.py
"""

import io
import os
import statistics
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from engine.alignment import assess_program  # noqa: E402
from engine.dataset import load_programs, parse_postings  # noqa: E402
from engine.demand import declining_skills, emerging_skills, trend_table  # noqa: E402
from engine.taxonomy import SkillExtractor, load_taxonomy  # noqa: E402
from generate_sample_data import ROLES, generate, write_csv  # noqa: E402

SEEDS = range(1, 21)
skills = load_taxonomy(os.path.join(ROOT, "data", "skills.json"))
extractor = SkillExtractor(skills)
programs = load_programs(os.path.join(ROOT, "data", "programs.json"), extractor)


def postings_for(seed, flat):
    buf = io.StringIO()
    write_csv(generate(seed, flat), buf)
    return parse_postings(buf.getvalue(), extractor)[0]


def naive_calls(table):
    """The first version's rule: thresholds on growth, no significance test."""
    up = [s for s, t in table.items() if t["share"] >= 0.05 and t["growth"] is not None and t["growth"] >= 0.3]
    down = [s for s, t in table.items() if (t["previous"] or 0) >= 0.05 and t["growth"] is not None
            and t["growth"] <= -0.2]
    return up, down


def truly_moving():
    """Skills whose probability the generator changes by 5+ points in some role."""
    rising, falling = set(), set()
    for _, _, profile in ROLES.values():
        for s, (p0, p1) in profile.items():
            if p1 - p0 >= 0.05:
                rising.add(s)
            if p0 - p1 >= 0.05:
                falling.add(s)
    return rising, falling


def main():
    rising, falling = truly_moving()
    null_new, null_old, null_advice = [], [], []
    hits = calls = 0
    scores = {p.id: [] for p in programs}
    grades = {p.id: [] for p in programs}

    for seed in SEEDS:
        flat = postings_for(seed, True)
        table = trend_table(flat)
        null_new.append(len(emerging_skills(table)) + len(declining_skills(table)))
        up, down = naive_calls(table)
        null_old.append(len(up) + len(down))
        null_advice.append(sum(1 for p in programs for r in assess_program(p, flat, skills)["recommendations"]
                               if r["action"] in ("Review", "Prepare")))

        trended = postings_for(seed, False)
        table = trend_table(trended)
        for s, _ in emerging_skills(table):
            calls += 1
            hits += s in rising
        for s, _ in declining_skills(table):
            calls += 1
            hits += s in falling
        for p in programs:
            r = assess_program(p, trended, skills)
            scores[p.id].append(r["score"])
            grades[p.id].append(r["grade"])

    lines = [
        "# Validation of the SkillAlign method",
        "",
        f"Generated by tools/validate.py over {len(SEEDS)} random samples of the synthetic generator.",
        "",
        "## 1. Null test: data with no trends at all",
        "",
        "| Method | Emerging + declining skills reported per sample (mean, max) |",
        "|---|---|",
        f"| First version: growth thresholds only | {statistics.mean(null_old):.1f}, {max(null_old)} |",
        f"| Now: significance test, Bonferroni, within-role check | {statistics.mean(null_new):.1f}, {max(null_new)} |",
        "",
        f"Review/Prepare advice issued on trend-free data, all 10 courses together: mean "
        f"{statistics.mean(null_advice):.1f} per sample, max {max(null_advice)}.",
        "",
        "## 2. Recovery on trended data",
        "",
        f"{calls} emerging/declining calls across all samples; {hits} of them "
        f"({(100 * hits / calls) if calls else 0:.0f}%) are skills the generator really moves.",
        "",
        f"The generator moves {len(rising | falling)} skills in at least one role; the tool reports about "
        f"{calls / len(SEEDS):.1f} per sample. It is deliberately cautious: small or role-specific changes are "
        f"not reported market-wide, and the course reports are where role-level changes show up.",
        "",
        "## 3. Stability of course scores across samples",
        "",
        "| Course | Score range | Mean | Most common grade (share of samples) |",
        "|---|---|---|---|",
    ]
    for p in sorted(programs, key=lambda p: statistics.mean(scores[p.id])):
        g = max(set(grades[p.id]), key=grades[p.id].count)
        lines.append(f"| {p.name} | {min(scores[p.id]):.1f} to {max(scores[p.id]):.1f} | "
                     f"{statistics.mean(scores[p.id]):.1f} | {g} ({100 * grades[p.id].count(g) / len(SEEDS):.0f}%) |")
    out = os.path.join(ROOT, "docs", "validation.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
